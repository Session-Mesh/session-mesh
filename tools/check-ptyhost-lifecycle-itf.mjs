import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtemp, readFile, readdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const model = join(root, "ocaml", "mesh_wire", "test", "ptyhost_lifecycle.qnt");
const fixturePath = join(root, "ocaml", "mesh_wire", "test", "ptyhost_lifecycle.itf.json");
const quint = join(root, "node_modules", ".bin", process.platform === "win32" ? "quint.cmd" : "quint");
const publicFields = [
  "attached",
  "attachment_mode",
  "client_count",
  "fanout_class",
  "io_class",
  "live",
  "mbt::actionTaken",
  "mbt::nondetPicks",
  "operation",
  "order_index",
  "queue_class",
  "replay_seen",
  "result_class",
  "reused",
  "size_class",
];
const quintTimeoutMs = 30_000;
const quintBackend = "typescript";

function runQuint(args, label, quintHome) {
  const result = spawnSync(quint, args, {
    cwd: root,
    encoding: "utf8",
    // Quint's Rust backend can provision an evaluator dynamically. Keep every
    // invocation in an empty, throwaway QUINT_HOME and force the tiny model
    // through the TypeScript backend shipped by the locked npm dependency.
    // A missing local backend therefore fails closed instead of falling back
    // to a download or a host-managed evaluator.
    env: { ...process.env, QUINT_HOME: quintHome },
    timeout: quintTimeoutMs,
  });
  if (result.error?.code === "ETIMEDOUT") {
    throw new Error(
      `${label} exceeded the ${quintTimeoutMs / 1000}s Quint process limit`,
    );
  }
  if (result.error) {
    throw new Error(`${label} could not start: ${result.error.message}`);
  }
  if (result.signal) {
    throw new Error(`${label} was terminated by ${result.signal}`);
  }
  assert.equal(
    result.status,
    0,
    `${label} failed:\n${result.stdout}\n${result.stderr}`,
  );
  return result.stdout.trim();
}

function normalise(trace, label) {
  assert.ok(Array.isArray(trace.vars), `${label}: ITF vars must be an array`);
  assert.deepEqual(
    [...new Set(trace.vars)].sort(),
    [...publicFields].sort(),
    `${label}: ITF must expose exactly the public lifecycle fields`,
  );
  assert.ok(Array.isArray(trace.states), `${label}: ITF states must be an array`);
  return trace.states.map((state, index) => {
    assert.deepEqual(
      Object.keys(state).filter((field) => field !== "#meta").sort(),
      [...publicFields].sort(),
      `${label}: state ${index} must expose exactly the public lifecycle fields`,
    );
    return Object.fromEntries(publicFields.map((field) => [field, state[field]]));
  });
}

const modelBytes = await readFile(model);
const fixture = JSON.parse(await readFile(fixturePath, "utf8"));
const quintHome = await mkdtemp(join(tmpdir(), "mesh-quint-home-"));
const outputDir = await mkdtemp(join(tmpdir(), "mesh-quint-"));
try {
  assert.equal(runQuint(["--version"], "Quint version", quintHome), "0.32.0");
  runQuint(["typecheck", model], "Quint typecheck", quintHome);
  assert.equal(fixture["#meta"]?.source, "ptyhost_lifecycle.qnt");
  assert.equal(fixture["#meta"]?.quint_version, "0.32.0");
  assert.equal(
    fixture["#meta"]?.source_sha256,
    createHash("sha256").update(modelBytes).digest("hex"),
    "fixture must bind the exact Quint source it replays",
  );
  runQuint(
    [
      "run", model,
      "--backend", quintBackend,
      "--main", "ptyhost_lifecycle",
      "--init", "init",
      "--step", "advance",
      "--max-steps", "15",
      "--max-samples", "1",
      "--n-traces", "1",
      "--seed", "20261007",
      "--mbt",
      "--out-itf", join(outputDir, "lifecycle_{seq}.itf.json"),
    ],
    "Quint lifecycle generation",
    quintHome,
  );
  const outputs = await readdir(outputDir);
  assert.deepEqual(outputs, ["lifecycle_0.itf.json"]);
  const generated = JSON.parse(await readFile(join(outputDir, outputs[0]), "utf8"));
  assert.deepEqual(
    normalise(generated, "generated ITF"),
    normalise(fixture, "checked-in ITF"),
    "the checked-in public ITF projection must be generated by the pinned Quint model",
  );
  assert.deepEqual(
    await readdir(quintHome),
    [],
    "the local TypeScript backend must not provision an evaluator in QUINT_HOME",
  );
} finally {
  await Promise.all([
    rm(quintHome, { recursive: true, force: true }),
    rm(outputDir, { recursive: true, force: true }),
  ]);
}
